using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class Move_Linear : EnemyMovement
{
    #region========================================( Variables )======================================================//
    /*-----[ Inspector Variables ]------------------------------------------------------------------------------------*/
    public Vector2 direction = Vector2.down;
    public float speed = 3f;
    public float acceleration;


    /*-----[ External Variables ]-------------------------------------------------------------------------------------*/


    /*-----[ Internal Variables ]-------------------------------------------------------------------------------------*/



    /*-----[ Reference Variables ]------------------------------------------------------------------------------------*/



    #endregion


    #region=======================================( Functions )======================================================= //

    /*-----[ Mono Functions ]-----------------------------------------------------------------------------------------*/
    

    /*-----[ Internal Functions ]-------------------------------------------------------------------------------------*/


    /*-----[ External Functions ]-------------------------------------------------------------------------------------*/
    public override Vector2 Offset(float t)
    {
        return direction.normalized * (speed * t + 0.5f * acceleration * t * t);
    }

    #endregion
}
