using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class Move_SineDescent : EnemyMovement
{
    #region========================================( Variables )======================================================//
    /*-----[ Inspector Variables ]------------------------------------------------------------------------------------*/
    public float fallSpeed = 2f;
    public float amplitude = 3f;
    public float frequency = 1f;

    /*-----[ External Variables ]-------------------------------------------------------------------------------------*/


    /*-----[ Internal Variables ]-------------------------------------------------------------------------------------*/



    /*-----[ Reference Variables ]------------------------------------------------------------------------------------*/



    #endregion


    #region=======================================( Functions )======================================================= //

    /*-----[ Mono Functions ]-----------------------------------------------------------------------------------------*/
    

    /*-----[ Internal Functions ]-------------------------------------------------------------------------------------*/


    /*-----[ External Functions ]-------------------------------------------------------------------------------------*/
    public override Vector2 Offset(float t) =>
        new Vector2(Mathf.Sin(t * frequency) * amplitude, -t * fallSpeed);

    #endregion
}
